#!/usr/bin/env bash
# Builds build/libh2d_native.a from native/h2d_native.c.  `bit build` runs this automatically
# ([build] -> native in Bit.hk).
#
# The archive is SELF-CONTAINED apart from SDL2 itself:
#  * images and TrueType fonts are handled by stb_image / stb_truetype (native/stb_*.h, public domain),
#    so SDL2_image, SDL2_ttf, freetype, libpng, ... are not needed at all;
#  * SDL2_gfx (and SDL2_mixer with H2D_WITH_AUDIO=1) are merged into libh2d_native.a from their static
#    .a files, so there is no libSDL2_gfx.so dependency either.
# SDL2 itself stays a shared library (it loads the video / audio drivers at run time).
#
# Anything that has no .a on this machine cannot be merged; it is then linked as a shared library
# instead, through src/h2d_syslibs.h# (regenerated here, it only contains `extern static [c, ...]` blocks).
set -euo pipefail
cd "$(dirname "$0")/.."
CC="${CC:-cc}"
AR="${AR:-ar}"
mkdir -p build
CFLAGS="${CFLAGS:--O2 -Wall -Wextra}"

PKGS="sdl2 SDL2_gfx"
ADDONS="SDL2_gfx"
# sound is opt-in: H2D_WITH_AUDIO=1 also needs SDL2_mixer
if [ "${H2D_WITH_AUDIO:-0}" = "1" ]; then
  PKGS="$PKGS SDL2_mixer"; ADDONS="$ADDONS SDL2_mixer"; CFLAGS="$CFLAGS -DH2D_WITH_AUDIO"
fi

# shellcheck disable=SC2046
$CC $CFLAGS -fPIC -c native/h2d_native.c -o build/h2d_native.o $(pkg-config --cflags $PKGS)

# ── where to look for lib<name>.a ──────────────────────────────────────────
LDIRS=()
for p in $ADDONS; do
  for f in $(pkg-config --static --libs-only-L "$p" 2>/dev/null || true); do LDIRS+=("${f#-L}"); done
done
multi="$($CC -print-multiarch 2>/dev/null || true)"
for d in ${multi:+/usr/lib/$multi} /usr/lib64 /usr/lib /usr/local/lib /lib64 /lib; do LDIRS+=("$d"); done

find_a() { local d; for d in "${LDIRS[@]}"; do [ -f "$d/lib$1.a" ] && { echo "$d/lib$1.a"; return 0; }; done; return 1; }

# libraries that must come from the system, never merged
DENY=" SDL2 m dl pthread rt c gcc gcc_s stdc++ X11 Xext Xcursor Xi Xfixes Xrandr Xrender Xss Xxf86vm Xinerama xcb Xau Xdmcp wayland-client wayland-egl wayland-cursor xkbcommon asound pulse pulse-simple jack sndio udev dbus-1 systemd drm gbm EGL GL GLESv2 GLX OpenGL decor-0 samplerate ibus-1.0 "

ARCHIVES=(); SHARED_PKGS=(); SHARED_LIBS=(); MERGED=()
add_unique() { local a; for a in "${ARCHIVES[@]:-}"; do [ "$a" = "$1" ] && return 0; done; ARCHIVES+=("$1"); }

for p in $ADDONS; do
  libs="$(pkg-config --static --libs-only-l "$p")"
  own="$(echo "$libs" | tr ' ' '\n' | grep -m1 -i "^-l${p}\$" || true)"; own="${own#-l}"
  if [ -z "$own" ] || ! find_a "$own" >/dev/null; then SHARED_PKGS+=("$p"); continue; fi
  for l in $libs; do
    n="${l#-l}"
    case "$DENY" in *" $n "*) continue ;; esac
    if a="$(find_a "$n")"; then add_unique "$a"; else SHARED_LIBS+=("$n"); fi
  done
  MERGED+=("$p")
done

# ── the archive: h2d_native.o + the merged static libraries ───────────────
rm -f build/libh2d_native.a
{
  echo "create build/libh2d_native.a"
  echo "addmod build/h2d_native.o"
  for a in "${ARCHIVES[@]:-}"; do [ -n "$a" ] && echo "addlib $a"; done
  echo "save"; echo "end"
} | $AR -M

# ── src/h2d_syslibs.h#: what is still linked as a shared library ──────────
{
  echo ";; GENERATED by h2d/native/build.sh on every build — do not edit."
  echo ";; Libraries that could not be merged into libh2d_native.a (no static .a on the build machine)"
  echo ";; and SDL2 itself, which stays shared on purpose."
  echo 'extern static [c, "sdl2"] is'
  echo 'end'
  for p in "${SHARED_PKGS[@]:-}"; do [ -n "$p" ] && printf 'extern static [c, "%s"] is\nend\n' "$p"; done
  for l in $(printf '%s\n' "${SHARED_LIBS[@]:-}" | sort -u); do [ -n "$l" ] && printf 'extern static [c, "%s"] is\nend\n' "$l"; done
} > src/h2d_syslibs.h#

echo "built build/libh2d_native.a"
echo "  statically merged : ${MERGED[*]:-none}  (+ ${#ARCHIVES[@]} archives)"
echo "  still shared      : sdl2 ${SHARED_PKGS[*]:-} ${SHARED_LIBS[*]:-}"
